-- 4) Largo de los textos de INCIDENTES.
--    DETALLES en CG_INCIDENTES es nvarchar(4000): ESPERADO 0 filas con mas de 4000 (si hay, el script de datos se detiene).
--    AVANCES pasa a nvarchar(max) en CG_INCIDENTES (Migracion_01): aqui solo se informa (se espera ver 10552 como maximo conocido).
SELECT 'INCIDENTES.DETALLES' AS CAMPO, COUNT(*) AS FILAS_MAS_DE_4000, MAX(LEN(DETALLES)) AS LARGO_MAXIMO FROM dbo.INCIDENTES WHERE LEN(DETALLES) > 4000
UNION ALL SELECT 'INCIDENTES.AVANCES (informativo)', COUNT(*), MAX(LEN(AVANCES)) FROM dbo.INCIDENTES WHERE LEN(AVANCES) > 4000;
-- Tipo actual de las columnas en CG_INCIDENTES (max_length = -1 significa nvarchar(max)):
SELECT c.name AS COLUMNA, t.name AS TIPO, c.max_length AS MAX_LENGTH FROM sys.columns c INNER JOIN sys.types t ON t.user_type_id = c.user_type_id
WHERE c.object_id = OBJECT_ID(N'dbo.CG_INCIDENTES') AND c.name IN (N'DETALLES', N'AVANCES');
GO

-- 5) CREACION -> int (dias desde 1900-01-01, sin hora; igual que FECHA_INGRESO). El script de datos detecta el tipo del origen:
--    datetime / date: DATEDIFF(DAY, '19000101', CREACION).   texto (nvarchar): numero (dias) o fecha en texto.
SELECT 'INCIDENTES' AS TABLA, TYPE_NAME(c.system_type_id) AS TIPO_ORIGEN, c.max_length AS MAX_LENGTH FROM sys.columns c WHERE c.object_id = OBJECT_ID(N'dbo.INCIDENTES') AND c.name = N'CREACION'
UNION ALL SELECT 'PROYECTOS', TYPE_NAME(c.system_type_id), c.max_length FROM sys.columns c WHERE c.object_id = OBJECT_ID(N'dbo.PROYECTOS') AND c.name = N'CREACION';
-- 5a) Clasificacion de formatos (origen texto). Formatos aceptados por el script de datos: dd/mm/aaaa [hora a.m./p.m.], aaaa-mm-dd, numero de dias.
SELECT 'INCIDENTES' AS TABLA,
       CASE WHEN NULLIF(LTRIM(RTRIM(CREACION)), '') IS NULL THEN '(vacio)'
            WHEN LTRIM(RTRIM(CREACION)) NOT LIKE '%[^0-9]%' THEN 'numero'
            WHEN LTRIM(RTRIM(CREACION)) LIKE '[0-3][0-9]/[01][0-9]/[12][0-9][0-9][0-9]%' THEN 'dd/mm/aaaa [hora]'
            WHEN LTRIM(RTRIM(CREACION)) LIKE '[12][0-9][0-9][0-9]-[01][0-9]-[0-3][0-9]%' THEN 'aaaa-mm-dd [hora]'
            ELSE 'OTRO FORMATO' END AS FORMATO, COUNT(*) AS FILAS, MIN(CREACION) AS EJEMPLO
FROM dbo.INCIDENTES GROUP BY CASE WHEN NULLIF(LTRIM(RTRIM(CREACION)), '') IS NULL THEN '(vacio)' WHEN LTRIM(RTRIM(CREACION)) NOT LIKE '%[^0-9]%' THEN 'numero' WHEN LTRIM(RTRIM(CREACION)) LIKE '[0-3][0-9]/[01][0-9]/[12][0-9][0-9][0-9]%' THEN 'dd/mm/aaaa [hora]' WHEN LTRIM(RTRIM(CREACION)) LIKE '[12][0-9][0-9][0-9]-[01][0-9]-[0-3][0-9]%' THEN 'aaaa-mm-dd [hora]' ELSE 'OTRO FORMATO' END
UNION ALL
SELECT 'PROYECTOS',
       CASE WHEN NULLIF(LTRIM(RTRIM(CREACION)), '') IS NULL THEN '(vacio)'
            WHEN LTRIM(RTRIM(CREACION)) NOT LIKE '%[^0-9]%' THEN 'numero'
            WHEN LTRIM(RTRIM(CREACION)) LIKE '[0-3][0-9]/[01][0-9]/[12][0-9][0-9][0-9]%' THEN 'dd/mm/aaaa [hora]'
            WHEN LTRIM(RTRIM(CREACION)) LIKE '[12][0-9][0-9][0-9]-[01][0-9]-[0-3][0-9]%' THEN 'aaaa-mm-dd [hora]'
            ELSE 'OTRO FORMATO' END, COUNT(*), MIN(CREACION)
FROM dbo.PROYECTOS GROUP BY CASE WHEN NULLIF(LTRIM(RTRIM(CREACION)), '') IS NULL THEN '(vacio)' WHEN LTRIM(RTRIM(CREACION)) NOT LIKE '%[^0-9]%' THEN 'numero' WHEN LTRIM(RTRIM(CREACION)) LIKE '[0-3][0-9]/[01][0-9]/[12][0-9][0-9][0-9]%' THEN 'dd/mm/aaaa [hora]' WHEN LTRIM(RTRIM(CREACION)) LIKE '[12][0-9][0-9][0-9]-[01][0-9]-[0-3][0-9]%' THEN 'aaaa-mm-dd [hora]' ELSE 'OTRO FORMATO' END;
-- 5b) Muestra del resultado: texto original y los dias desde 1900 que se guardarian (solo filas con formato dd/mm/aaaa)
SELECT TOP 10 'INCIDENTES' AS TABLA, ID, CREACION AS ORIGEN, DATEDIFF(DAY, '19000101', TRY_CONVERT(date, LEFT(LTRIM(RTRIM(CREACION)), 10), 103)) AS DIAS_DESDE_1900, TRY_CONVERT(date, LEFT(LTRIM(RTRIM(CREACION)), 10), 103) AS FECHA_RESULTANTE
FROM dbo.INCIDENTES WHERE LTRIM(RTRIM(CREACION)) LIKE '[0-3][0-9]/[01][0-9]/[12][0-9][0-9][0-9]%' ORDER BY ID;
SELECT TOP 10 'PROYECTOS' AS TABLA, ID, CREACION AS ORIGEN, DATEDIFF(DAY, '19000101', TRY_CONVERT(date, LEFT(LTRIM(RTRIM(CREACION)), 10), 103)) AS DIAS_DESDE_1900, TRY_CONVERT(date, LEFT(LTRIM(RTRIM(CREACION)), 10), 103) AS FECHA_RESULTANTE
FROM dbo.PROYECTOS WHERE LTRIM(RTRIM(CREACION)) LIKE '[0-3][0-9]/[01][0-9]/[12][0-9][0-9][0-9]%' ORDER BY ID;
GO

