-- 7) RELAINC (historial de avances -> CG_AVANCES) ----------------------------------------------------------
-- 7a) IDUSUARIO: login (texto) o id numerico? El script de datos: numerico -> login por CG_COR_RESPONSABLES; texto -> se usa como login.
SELECT TOP 15 IDUSUARIO, COUNT(*) AS FILAS, MAX(CASE WHEN TRY_CAST(IDUSUARIO AS INT) IS NULL THEN 'TEXTO (login)' ELSE 'NUMERICO (id)' END) AS INTERPRETACION
FROM dbo.RELAINC GROUP BY IDUSUARIO ORDER BY COUNT(*) DESC;
-- 7b) RESPONSABLE: valores presentes (en CG_AVANCES es varchar(10): FUNCIONAL / TECNICO / CLIENTE). ESPERADO: solo esos
SELECT RESPONSABLE, COUNT(*) AS FILAS FROM dbo.RELAINC GROUP BY RESPONSABLE ORDER BY COUNT(*) DESC;
-- 7c) DESCRIPCION pasa de nvarchar a varchar: filas con caracteres que no existen en el codepage (se perderian). ESPERADO: 0
SELECT COUNT(*) AS FILAS_CON_CARACTERES_PERDIDOS FROM dbo.RELAINC WHERE DESCRIPCION <> CAST(CAST(DESCRIPCION AS VARCHAR(4000)) AS NVARCHAR(4000));
-- 7d) Tipos de objeto presentes (el script usa 'inc' y 'proy'): ESPERADO: inc / proy
SELECT TIPOOBJETO, COUNT(*) AS FILAS FROM dbo.RELAINC GROUP BY TIPOOBJETO;
GO

-- 8) Claves foraneas hacia las CG_ que se van a vaciar (todas deben estar entre las dependientes del script 02) ---
SELECT OBJECT_NAME(fk.parent_object_id) AS TABLA_HIJA, fk.name AS CLAVE, OBJECT_NAME(fk.referenced_object_id) AS TABLA_PADRE
FROM sys.foreign_keys fk
WHERE OBJECT_NAME(fk.referenced_object_id) LIKE 'CG[_]%' OR OBJECT_NAME(fk.parent_object_id) LIKE 'CG[_]%'
ORDER BY 3, 1;
GO
