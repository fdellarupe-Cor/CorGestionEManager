DECLARE @sql NVARCHAR(MAX), @colEst SYSNAME, @m INT, @n INT, @tipoCrea SYSNAME, @creaExpr NVARCHAR(MAX);

BEGIN TRAN;

-- ===== 1) CONTROLES =====
IF NOT EXISTS (SELECT 1 FROM dbo.CG_COR_RESPONSABLES WHERE NULLIF(LTRIM(RTRIM(ID_SEG)), '') IS NOT NULL)
BEGIN RAISERROR('CG_COR_RESPONSABLES esta vacia o sin ID_SEG: no hay equivalencia de responsables.', 16, 1); ROLLBACK TRAN; RETURN; END

IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID(N'dbo.CG_INCIDENTES') AND name = N'AVANCES' AND max_length <> -1)
BEGIN RAISERROR('CG_INCIDENTES.AVANCES todavia no es nvarchar(max): ejecutar antes Migracion_01_Estructura.sql.', 16, 1); ROLLBACK TRAN; RETURN; END

SELECT @n = COUNT(*) FROM dbo.INCIDENTES WHERE LEN(DETALLES) > 4000;
IF @n > 0
BEGIN RAISERROR('INCIDENTES: hay %d filas con DETALLES de mas de 4000 caracteres (CG_INCIDENTES admite 4000).', 16, 1, @n); ROLLBACK TRAN; RETURN; END

SELECT @tipoCrea = TYPE_NAME(c.system_type_id) FROM sys.columns c WHERE c.object_id = OBJECT_ID(N'dbo.INCIDENTES') AND c.name = N'CREACION';
IF @tipoCrea IN ('nvarchar', 'varchar', 'nchar', 'char')   -- si es datetime/date se convierte con DATEDIFF y no hay nada que validar
BEGIN
    -- Formatos aceptados: dd/mm/aaaa [hh:mm:ss a.m./p.m.] (estilo 103, sin ambiguedad dia/mes), aaaa-mm-dd, o numero de dias desde 1900.
    SELECT @n = COUNT(*) FROM dbo.INCIDENTES o WHERE NULLIF(LTRIM(RTRIM(o.CREACION)), '') IS NOT NULL AND LTRIM(RTRIM(o.CREACION)) <> '0' AND (CASE WHEN NULLIF(LTRIM(RTRIM(o.CREACION)), '') IS NULL THEN NULL WHEN LTRIM(RTRIM(o.CREACION)) NOT LIKE '%[^0-9]%' THEN CASE WHEN TRY_CAST(LTRIM(RTRIM(o.CREACION)) AS INT) BETWEEN 1 AND 100000 THEN TRY_CAST(LTRIM(RTRIM(o.CREACION)) AS INT) ELSE NULL END WHEN LTRIM(RTRIM(o.CREACION)) LIKE '[0-3][0-9]/[01][0-9]/[12][0-9][0-9][0-9]%' THEN DATEDIFF(DAY, '19000101', TRY_CONVERT(date, LEFT(LTRIM(RTRIM(o.CREACION)), 10), 103)) WHEN LTRIM(RTRIM(o.CREACION)) LIKE '[12][0-9][0-9][0-9]-[01][0-9]-[0-3][0-9]%' THEN DATEDIFF(DAY, '19000101', TRY_CONVERT(date, LEFT(LTRIM(RTRIM(o.CREACION)), 10), 23)) ELSE NULL END) IS NULL;
    IF @n > 0
    BEGIN
        SELECT TOP 20 o.ID, o.CREACION AS INCIDENTES_CREACION_NO_CONVERTIBLE FROM dbo.INCIDENTES o WHERE NULLIF(LTRIM(RTRIM(o.CREACION)), '') IS NOT NULL AND LTRIM(RTRIM(o.CREACION)) <> '0' AND (CASE WHEN NULLIF(LTRIM(RTRIM(o.CREACION)), '') IS NULL THEN NULL WHEN LTRIM(RTRIM(o.CREACION)) NOT LIKE '%[^0-9]%' THEN CASE WHEN TRY_CAST(LTRIM(RTRIM(o.CREACION)) AS INT) BETWEEN 1 AND 100000 THEN TRY_CAST(LTRIM(RTRIM(o.CREACION)) AS INT) ELSE NULL END WHEN LTRIM(RTRIM(o.CREACION)) LIKE '[0-3][0-9]/[01][0-9]/[12][0-9][0-9][0-9]%' THEN DATEDIFF(DAY, '19000101', TRY_CONVERT(date, LEFT(LTRIM(RTRIM(o.CREACION)), 10), 103)) WHEN LTRIM(RTRIM(o.CREACION)) LIKE '[12][0-9][0-9][0-9]-[01][0-9]-[0-3][0-9]%' THEN DATEDIFF(DAY, '19000101', TRY_CONVERT(date, LEFT(LTRIM(RTRIM(o.CREACION)), 10), 23)) ELSE NULL END) IS NULL ORDER BY o.ID;
        RAISERROR('INCIDENTES.CREACION: %d valores no se pueden convertir (formatos validos: dd/mm/aaaa [hora], aaaa-mm-dd o numero de dias). Ver la lista de arriba.', 16, 1, @n); ROLLBACK TRAN; RETURN;
    END
END

SELECT @tipoCrea = TYPE_NAME(c.system_type_id) FROM sys.columns c WHERE c.object_id = OBJECT_ID(N'dbo.PROYECTOS') AND c.name = N'CREACION';
IF @tipoCrea IN ('nvarchar', 'varchar', 'nchar', 'char')   -- si es datetime/date se convierte con DATEDIFF y no hay nada que validar
BEGIN
    -- Formatos aceptados: dd/mm/aaaa [hh:mm:ss a.m./p.m.] (estilo 103, sin ambiguedad dia/mes), aaaa-mm-dd, o numero de dias desde 1900.
    SELECT @n = COUNT(*) FROM dbo.PROYECTOS o WHERE NULLIF(LTRIM(RTRIM(o.CREACION)), '') IS NOT NULL AND LTRIM(RTRIM(o.CREACION)) <> '0' AND (CASE WHEN NULLIF(LTRIM(RTRIM(o.CREACION)), '') IS NULL THEN NULL WHEN LTRIM(RTRIM(o.CREACION)) NOT LIKE '%[^0-9]%' THEN CASE WHEN TRY_CAST(LTRIM(RTRIM(o.CREACION)) AS INT) BETWEEN 1 AND 100000 THEN TRY_CAST(LTRIM(RTRIM(o.CREACION)) AS INT) ELSE NULL END WHEN LTRIM(RTRIM(o.CREACION)) LIKE '[0-3][0-9]/[01][0-9]/[12][0-9][0-9][0-9]%' THEN DATEDIFF(DAY, '19000101', TRY_CONVERT(date, LEFT(LTRIM(RTRIM(o.CREACION)), 10), 103)) WHEN LTRIM(RTRIM(o.CREACION)) LIKE '[12][0-9][0-9][0-9]-[01][0-9]-[0-3][0-9]%' THEN DATEDIFF(DAY, '19000101', TRY_CONVERT(date, LEFT(LTRIM(RTRIM(o.CREACION)), 10), 23)) ELSE NULL END) IS NULL;
    IF @n > 0
    BEGIN
        SELECT TOP 20 o.ID, o.CREACION AS PROYECTOS_CREACION_NO_CONVERTIBLE FROM dbo.PROYECTOS o WHERE NULLIF(LTRIM(RTRIM(o.CREACION)), '') IS NOT NULL AND LTRIM(RTRIM(o.CREACION)) <> '0' AND (CASE WHEN NULLIF(LTRIM(RTRIM(o.CREACION)), '') IS NULL THEN NULL WHEN LTRIM(RTRIM(o.CREACION)) NOT LIKE '%[^0-9]%' THEN CASE WHEN TRY_CAST(LTRIM(RTRIM(o.CREACION)) AS INT) BETWEEN 1 AND 100000 THEN TRY_CAST(LTRIM(RTRIM(o.CREACION)) AS INT) ELSE NULL END WHEN LTRIM(RTRIM(o.CREACION)) LIKE '[0-3][0-9]/[01][0-9]/[12][0-9][0-9][0-9]%' THEN DATEDIFF(DAY, '19000101', TRY_CONVERT(date, LEFT(LTRIM(RTRIM(o.CREACION)), 10), 103)) WHEN LTRIM(RTRIM(o.CREACION)) LIKE '[12][0-9][0-9][0-9]-[01][0-9]-[0-3][0-9]%' THEN DATEDIFF(DAY, '19000101', TRY_CONVERT(date, LEFT(LTRIM(RTRIM(o.CREACION)), 10), 23)) ELSE NULL END) IS NULL ORDER BY o.ID;
        RAISERROR('PROYECTOS.CREACION: %d valores no se pueden convertir (formatos validos: dd/mm/aaaa [hora], aaaa-mm-dd o numero de dias). Ver la lista de arriba.', 16, 1, @n); ROLLBACK TRAN; RETURN;
    END
