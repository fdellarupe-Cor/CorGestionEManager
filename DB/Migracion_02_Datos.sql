/* =====================================================================
   Migracion_02_Datos.sql  -  vacia las CG_ de prueba y carga los datos de las 17 tablas originales de prod

   ESTADO: SCRIPT PARA REVISAR. NO SE EJECUTO.
   Base: dbcordatv485Cor.   Requisitos: Migracion_01_Estructura.sql ya ejecutado y Migracion_00_Diagnostico.sql revisado.
   TODO EN UNA SOLA TRANSACCION y UN SOLO LOTE (sin GO): termina en ROLLBACK. Revisar los resultados y, si estan bien,
   cambiar la ultima instruccion ROLLBACK TRAN por COMMIT TRAN y ejecutar de nuevo.

   1) CONTROLES (si falla alguno, se detiene SIN tocar nada):
        - CG_COR_RESPONSABLES debe tener datos (equivalencia id -> login).
        - CG_INCIDENTES.AVANCES debe ser nvarchar(max) (lo hace Migracion_01; en prod hay avances de mas de 4000 caracteres).
        - INCIDENTES.DETALLES de 4000 caracteres o menos (en CG_INCIDENTES es nvarchar(4000)).
        - INCIDENTES.CREACION y PROYECTOS.CREACION: si el origen es texto, deben tener un formato conocido (ver abajo); si no, se detiene y
          muestra los primeros 20 valores problematicos.
          Si el origen es datetime/date no hay nada que validar.
   2) VACIADO (DELETE, en orden seguro por las claves foraneas) de: CG_AGENDA_SUBTEMA, CG_AGENDA_CORRESPONSABLE, CG_AGENDA, CG_INCIDENTES, CG_PROYECTOS, CG_AVANCES, CG_APL_RELAC, CG_APL, CG_LICENCIAS, CG_ESTADISTICAS, CG_CLIENTES_DET, CG_CLIEN_X_APLIC, CG_CONTACTOS, CG_CLIENTES, CG_APLICATIVOS, CG_BROWSERS, CG_PRIORIDADES, CG_VIA_PEDIDO, CG_TIPO_APL.
      NO SE TOCAN: CG_ESTADOS, CG_COR_RESPONSABLES, CG_TIPO_AVANCE, CG_TIPO_ACCION, CG_RELAOBJ, CG_MENU*, CG_USUARIOS, CG_FERIADOS.
   3) CARGA (padres primero) con IDENTITY_INSERT: se conservan TODOS los ids originales; despues se reposiciona la identidad.
      Transformaciones:
        - ESTADO <- VER (o ESTADO si ya se renombro; NULL = 1) en AGENDA, APL, INCIDENTES y PROYECTOS; 1 en las demas.
        - Responsables (id numerico) -> login (*_SEG) por CG_COR_RESPONSABLES: RESPON_GESTION_SEG, RESPON_TEC_SEG, ID_RESPON_SEG,
          RESPON_ENVIO_SEG, ULT_ACC_USR_SEG. Un id sin equivalencia queda en NULL (ver el diagnostico, punto 6).
        - INCIDENTES.RESPONSABLE / PROYECTOS.RESPONSABLE <- RESPONSABLE del ultimo avance (RELAINC); si no hay, FUNCIONAL.
        - CREACION -> int (dias desde 1900-01-01, sin hora). En prod es texto: dd/mm/aaaa [hh:mm:ss a.m./p.m.] se lee con estilo 103 (dia/mes sin
          ambiguedad, sin depender del idioma de la sesion); tambien aaaa-mm-dd y numero de dias. Si fuera datetime/date: DATEDIFF. TIPO_PROY = 1. AMBIENTE, ESTADO_CLIENTE, TIEMPO_FUNC/DESA = NULL (no existian).
        - RELAINC -> CG_AVANCES: IDUSUARIO (texto) -> IDUSUARIO (si es numerico) e IDUSUARIO_SEG (login: el texto, o el id por
          CG_COR_RESPONSABLES); FECHAREGISTRO date -> dias desde 1900; RESPONSABLE a 10 caracteres en mayuscula.
        - AGENDA: se copia como los recordatorios que crea sp_cg_Agenda 'insertar' (sin datos de reunion).
   4) Resultado final: conteo original vs CG_ por tabla (deben ser iguales) y avisos de datos sin equivalencia.
   REVERSA: antes del COMMIT, ROLLBACK. Despues del COMMIT las originales siguen intactas: se puede repetir el script.
   ===================================================================== */

